export const DAILY_WORDS = VOCABULARY_LIST;

export function getDailyWord(offset: number = 0): SanskritWord {
  // Use day of year or modulo with offset to enable deterministic daily word or user cycling
  const today = new Date();
  const startOfYear = new Date(today.getFullYear(), 0, 1);
  const dayIndex = Math.floor((today.getTime() - startOfYear.getTime()) / (1000 * 60 * 60 * 24));
  const selectedIndex = (Math.abs(dayIndex + offset)) % DAILY_WORDS.length;
  return DAILY_WORDS[selectedIndex];
}
